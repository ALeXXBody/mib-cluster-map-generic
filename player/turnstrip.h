/* Draw one glyph at (gx, gy) at the given luma, into pY (w*height). */
static void ts_glyph(uint8_t* pY, int w, int h, int gx, int gy,
                     const unsigned char* g, uint8_t on)
{
    int row, col;
    for (row = 0; row < 7; ++row) {
        uint8_t bits = g[row];
        for (col = 0; col < 5; ++col) {
            int x = gx + col, y = gy + row;
            if (x < 0 || x >= w || y < 0 || y >= h) continue;
            if (bits & (0x80 >> col)) pY[y * w + x] = on;
        }
    }
}

/* Draw a dark backing bar (border) and the line of text, bottom-centred. */
static void ts_draw(uint8_t* pY, int w, int h)
{
    static const int SCALE = 3;      // text is drawn at 5x7 cells x3 => 15x21
    static const int PAD   = 2;      // border thickness per side
    char safe[64];                   // only printable characters, capped
    int glyphs = 0;
    int gx, i;

    const int gh   = 7 * SCALE;      // 21
    const int gw   = 5 * SCALE;      // 15
    const int bh   = gh + 2 * PAD;   // 25 (border)
    const int by   = h - bh - 6;     // 6 px above the window's bottom edge
    const int bw   = w - 2 * PAD;    // border bar spans most of the width

    if (ts_text[0] == 0) return;
    if (by < 0) return;

    /* Clean copy: keep 0x20..0x7E, replace everything else with a space. */
    for (i = 0; ts_text[i] != 0 && glyphs + 1 < (int)sizeof safe; ++i) {
        unsigned ch = (unsigned char)ts_text[i];
        safe[glyphs++] = (ch < 0x20u || ch > 0x7Eu) ? (char)' ' : (char)ch;
    }
    safe[glyphs] = 0;

    int text_w = glyphs * (gw + SCALE) - SCALE;  // glyphs + 3 px letter spacing
    if (text_w > bw) text_w = bw;

    /* Dark luma bar + darker edges */
    for (int y = by; y < h - 6 && y < by + bh; ++y)
        memset(pY + y * w + PAD, 16, bw);

    gx = (w - text_w) / 2;
    for (i = 0; i < glyphs; ++i) {
        unsigned ch = (unsigned char)safe[i];
        if (ch != ' ') ts_glyph(pY, w, h, gx, by + PAD, font5x7[ch - 0x20], 255);
        gx += gw + SCALE;
    }
}

