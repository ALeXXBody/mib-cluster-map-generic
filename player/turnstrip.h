/* turnstrip.h — the fork player's "Turn info in the info bar" strip.
 *
 * What the hook already decoded from the AA navigation channel gets a row
 * at the bottom of the cluster frame: road name | ETA | distance
 * (/tmp/gal_nav_info, written video_sink_hook.c.WriteNavInfo when
 * GAL_NAV_INFO_FILE=1). The control file /tmp/stream-player.navstrip
 * ("1"/"0") turns the strip on live, and the Addon's Turn-info switch sets
 * both.
 *
 * Drawing is straight into the Y plane of the decoded frame (luma only:
 * white glyph pixels as 255, a black 1 px border around the strip as 16).
 * No extra GL state, shader, texture, or allocation.
 *
 * The 5x7 font data: the classic public LiquidCrystal font values
 * (Adafruit's 5x7 LCD font table, our transcription — noted in NOTICE.md).
 * Glyph for c = font5x7[c-0x20][col], column top-to-bottom.
 *
 * Everything here is static; no heap. There is no caller yet: a single
 * call site inside the render loop (see opengl_gpu.cc) drives it.
 */
#include <stdio.h>
#include <string.h>

/* --- state ------------------------------------------------------------- */
static int  ts_on = 0;          // 0 = hidden
static int  ts_on_known = 0;
static char ts_text[200] = "";
static uint64_t ts_last_poll_us = 0;

/* --- control files ------------------------------------------------------ */
static void ts_poll(uint64_t now_us)
{
    if (ts_last_poll_us != 0 && now_us - ts_last_poll_us < 1000000ULL) return;
    ts_last_poll_us = now_us;

    FILE* f = fopen("/tmp/stream-player.navstrip", "r");
    if (f) {
        int v = 0;
        if (fscanf(f, "%d", &v) == 1) { ts_on = (v != 0); ts_on_known = 1; }
        fclose(f);
    }
    f = fopen("/tmp/gal_nav_info", "r");
    if (f) {
        char line[200];
        memset(line, 0, sizeof line);
        size_t n = 0;
        int c;
        while (n + 1 < sizeof line && (c = fgetc(f)) != EOF) line[n++] = (char)c;
        fclose(f);
        while (n && (line[n-1] == '\n' || line[n-1] == '\r' || line[n-1] == ' ')) line[--n] = 0;
        line[n] = 0;
        if (n == 0) return;
        if (strcmp(line, "STOP") == 0) {
            ts_text[0] = 0;
        } else if (strcmp(line, ts_text) != 0) {
            memcpy(ts_text, line, n + 1);
        }
    }
}

